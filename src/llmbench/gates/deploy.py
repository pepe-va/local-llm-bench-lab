"""The winning configuration as something you can run: a llama-server command and a unit."""

import shlex
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

from llmbench.analysis.view import ConfigRow
from llmbench.config.llama import LlamaConfig
from llmbench.llamacpp.argv import sampling_flags, server_argv


@dataclass(frozen=True)
class Deployment:
    argv: list[str]
    ignored: list[str]

    @property
    def command(self) -> str:
        return " \\\n  ".join(_pairs(self.argv))

    def systemd_unit(self, name: str = "llama-server") -> str:
        return f"""[Unit]
Description={name} (generated by llb)
After=network.target

[Service]
ExecStart={shlex.join(self.argv)}
Restart=on-failure
Nice=-5

[Install]
WantedBy=multi-user.target
"""


def deployment(row: ConfigRow, *, port: int = 8080) -> Deployment:
    cfg_data: dict[str, Any] = {k: v for k, v in row.config.items() if k != "effective_sampling"}
    cfg = LlamaConfig.model_validate(cfg_data)
    server_bin = _server_binary(row)
    model = Path(str(row.model.get("path", "model.gguf")))
    draft = cast(dict[str, Any], row.model.get("draft") or {}).get("path")
    argv = server_argv(
        server_bin, model, cfg, port=port, draft_model=Path(str(draft)) if draft else None
    )
    sampling = _effective_sampling(row) or cfg.sampling.body()
    samp = sampling_flags(sampling)
    # benchmark-only flags are dropped: deployed servers keep their web UI off but metrics on
    return Deployment([*argv.args, *samp.args], argv.ignored + samp.ignored)


def _server_binary(row: ConfigRow) -> Path:
    argvs = [cast(list[str], run.get("argv") or []) for run in row.runs]
    for argv in argvs:
        if argv and argv[0].endswith("llama-server"):
            return Path(argv[0])
    for argv in argvs:
        if argv:
            return Path(argv[0]).parent / "llama-server"
    return Path("llama-server")


def _effective_sampling(row: ConfigRow) -> dict[str, Any] | None:
    for run in row.runs:
        cfg = cast(dict[str, Any], run.get("config") or {})
        if "effective_sampling" in cfg:
            body = dict(cast(dict[str, Any], cfg["effective_sampling"]))
            body.pop("ignore_eos", None)  # a benchmark convenience, not a serving default
            return body
    return None


def _pairs(argv: list[str]) -> list[str]:
    """Group `--flag value` pairs on one line each, for a readable shell command."""
    out: list[str] = [shlex.quote(argv[0])]
    i = 1
    while i < len(argv):
        tok = argv[i]
        nxt = argv[i + 1] if i + 1 < len(argv) else None
        if nxt is not None and not (nxt.startswith("-") and not _is_number(nxt)):
            out.append(f"{tok} {shlex.quote(nxt)}")
            i += 2
        else:
            out.append(tok)
            i += 1
    return out


def _is_number(s: str) -> bool:
    try:
        float(s)
    except ValueError:
        return False
    return True
