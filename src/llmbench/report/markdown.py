"""Markdown report and guidance (no optional dependencies)."""

from typing import Any

from llmbench.report.data import ReportData


def _fmt(v: Any, digits: int = 1) -> str:
    if v is None:
        return "-"
    if isinstance(v, bool):
        return "yes" if v else ""
    if isinstance(v, float):
        return f"{v:.{digits}f}"
    return str(v)


def _ci(low: float | None, high: float | None) -> str:
    return f"[{low:.2f}, {high:.2f}]" if low is not None and high is not None else "-"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(c.replace("|", "\\|") for c in r) + " |" for r in rows]
    return "\n".join(out)


def bench_table(d: ReportData) -> str:
    return _table(
        ["model", "quant", "build", "variant", "test", "t/s", "±", "95% CI", "median", "IQR", "cv",
         "unstable", "peak RSS MB"],
        [
            [r["model"], _fmt(r["quant"]), r["build"], r["variant"], r["test"], _fmt(r["tps"], 2),
             _fmt(r["stddev"], 2), _ci(r["ci_low"], r["ci_high"]), _fmt(r["median"], 2),
             _fmt(r["iqr"], 2), f"{r['cv']:.1%}", _fmt(r["unstable"]), _fmt(r["rss_mb"], 0)]
            for r in d.bench
        ],
    )  # fmt: skip


def latency_table(d: ReportData) -> str:
    return _table(
        ["model", "quant", "variant", "suite", "TTFT p50 ms", "TTFT p95 ms", "ITL p50 ms",
         "gen t/s", "prompt t/s", "e2e p50 ms"],
        [
            [r["model"], _fmt(r["quant"]), r["variant"], r["suite"], _fmt(r.get("ttft_ms_p50")),
             _fmt(r.get("ttft_ms_p95")), _fmt(r.get("itl_ms_p50"), 2), _fmt(r.get("gen_tps_mean")),
             _fmt(r.get("prompt_tps_mean")), _fmt(r.get("e2e_ms_p50"))]
            for r in d.latency
        ],
    )  # fmt: skip


def quality_table(d: ReportData) -> str:
    return _table(
        ["model", "quant", "variant", "suite", "score", "pass rate", "judge", "spearman", "nDCG",
         "MRR", "gen t/s", "words/s"],
        [
            [r["model"], _fmt(r["quant"]), r["variant"], r["suite"], _fmt(r.get("score_mean"), 3),
             _pct(r.get("pass_rate")), _fmt(r.get("judge.overall_mean"), 2),
             _fmt(r.get("spearman"), 3), _fmt(r.get("ndcg"), 3), _fmt(r.get("mrr"), 3),
             _fmt(r.get("gen_tps_mean")), _fmt(r.get("words_per_s_mean"))]
            for r in d.quality
        ],
    )  # fmt: skip


def serving_table(d: ReportData) -> str:
    return _table(
        ["model", "variant", "suite", "c", "req/s", "gen t/s (aggregate)", "TTFT p50", "TTFT p95",
         "e2e p95", "errors"],
        [
            [r["model"], r["variant"], r["suite"], _fmt(r.get("c")),
             _fmt(r.get("requests_per_s"), 2), _fmt(r.get("gen_tps_aggregate")),
             _fmt(r.get("ttft_ms_p50")), _fmt(r.get("ttft_ms_p95")), _fmt(r.get("e2e_ms_p95")),
             _pct(r.get("error_rate"))]
            for r in d.serving
        ],
    )  # fmt: skip


def lm_eval_table(d: ReportData) -> str:
    return _table(
        ["model", "variant", "task.metric", "value"],
        [[r["model"], r["variant"], r["metric"], _fmt(r["value"], 4)] for r in d.lm_eval],
    )


def gates_table(d: ReportData) -> str:
    rows: list[list[str]] = []
    for v in d.verdicts:
        mark = "✅" if v.passed else "❌"
        star = " ⭐" if d.winner is v else ""
        rows.append([f"{mark}{star}", v.row.label, "; ".join(c.text for c in v.checks) or "-",
                     "; ".join(v.reasons) or ""])  # fmt: skip
    return _table(["", "configuration", "values", "failed because"], rows)


def _pct(v: Any) -> str:
    return "-" if v is None else f"{float(v):.0%}"


def render_markdown(d: ReportData) -> str:
    parts = [
        f"# {d.experiment}",
        f"_Generated by llb {d.llb_version} at {d.generated_at} · "
        f"{len(d.rows)} configurations · {d.runs} runs · {len(d.failures)} failed_",
        _machine_line(d),
    ]
    if d.verdicts:
        parts += ["## Gates", gates_table(d)]
        if d.winner and d.deploy:
            parts += ["### Winner", f"**{d.winner.row.label}**", "```bash", d.deploy.command, "```"]
    if d.bench:
        parts += ["## Bench (llama-bench)", bench_table(d)]
    if d.latency:
        parts += ["## Latency (llama-server)", latency_table(d)]
    if d.quality:
        parts += [
            "## Quality",
            "_Judge scores (1-5) are subjective (LLM-as-judge) and kept apart from objective "
            "scores (0-1)._",
            quality_table(d),
        ]
    if d.serving:
        parts += ["## Serving (concurrent load)", serving_table(d)]
    if d.lm_eval:
        parts += ["## lm-evaluation-harness", lm_eval_table(d)]
    if d.failures:
        parts += [
            "## Failed runs",
            _table(
                ["phase", "configuration", "suite", "status", "error"],
                [
                    [f["phase"], f["config"], _fmt(f.get("suite")), f["status"], f["error"]]
                    for f in d.failures
                ],
            ),
        ]
    return "\n\n".join(parts) + "\n"


def _machine_line(d: ReportData) -> str:
    m = d.machine
    if not m:
        return ""
    return (
        f"Machine: **{m.get('cpu_model') or m.get('machine')}** · {m.get('os')} · "
        f"{m.get('cpu_count')} CPUs · {m.get('ram_total_mb')} MB RAM · governor {m.get('governor')}"
    )


def render_guidance(d: ReportData) -> str:
    """What to deploy and why (`llb guide`)."""
    parts = [f"# Guidance: {d.experiment}", _machine_line(d)]
    if not d.gates:
        parts.append("_No gates defined: every configuration is listed as passing._")
    passed = [v for v in d.verdicts if v.passed]
    parts.append(f"**{len(passed)} of {len(d.verdicts)}** configurations pass every gate.")
    if d.gates:
        parts.append(
            "Gates:\n" + "\n".join(f"- `{g.metric}` ({g.agg}) {g.op} {g.value:g}" for g in d.gates)
        )
    parts += ["## Results", gates_table(d)]
    if d.winner and d.deploy:
        sel = d.select
        why = (
            f"best `{sel.metric}` ({sel.objective}) among {sel.among} configurations"
            if sel
            else "the only configuration that passed"
        )
        parts += [
            "## Recommended configuration",
            f"**{d.winner.row.label}** ({why}).",
            "Run it with:",
            "```bash",
            d.deploy.command,
            "```",
            "Listens on 127.0.0.1 only. Use `--host 0.0.0.0` only on a trusted network, "
            "never exposed to the Internet.",
            "As a systemd service (`/etc/systemd/system/llama-server.service`):",
            "```ini",
            d.deploy.systemd_unit(),
            "```",
        ]
        if d.deploy.ignored:
            parts.append(
                "Not representable as server flags (send them per request): "
                + ", ".join(f"`{x}`" for x in d.deploy.ignored)
            )
    else:
        parts += ["## Recommended configuration", "None: no configuration passed the gates."]
    return "\n\n".join(p for p in parts if p) + "\n"
